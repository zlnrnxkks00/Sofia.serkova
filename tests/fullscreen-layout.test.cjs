const assert = require('node:assert/strict');
const fs = require('node:fs');
const root = 'dist/';
const html = fs.readFileSync(root + 'index.html', 'utf8');
const css = fs.readFileSync(root + 'styles.css', 'utf8');
const sections = [...html.matchAll(/<section class="([^"]+)" id="([^"]+)"/g)];
const full = sections.filter(match => match[1].includes('viewport-section')).map(match => match[2]);
assert.deepEqual(full, ['home', 'my-history', 'touch', 'reviews', 'contact']);
['expertise', 'for-you', 'services', 'principle', 'questions'].forEach(id => {
  const section = sections.find(match => match[2] === id);
  assert(section && !section[1].includes('viewport-section'), `${id} remains content-sized`);
});
assert(css.includes('scroll-snap-type:none') && !css.includes('scroll-snap-type:y mandatory'));
assert(/\.statement\{[^}]*height:auto/.test(css));
assert(/\.statement\{width:100%;height:auto;margin:0/.test(css));
assert(/\.questions\.section\{padding:40px 0 48px\}/.test(css));
assert(/\.price-note span\{[^}]*font-size:16px/.test(css));
assert(/\.viewport-section#reviews \.section-kicker\{padding-bottom:48px\}/.test(css));
assert(/\.reviews-grid\{column-count:1;column-gap:0\}/.test(css));
['monitor', 'laptop', 'tablet', 'phone'].forEach(kind => assert(css.includes(`--device-kind:${kind}`)));
assert(html.includes('class="review-stand" aria-hidden="true"'));
assert(html.includes('class="review-device-base" aria-hidden="true"'));
assert(html.includes('role="region" aria-label="Рассказ Софии"'));
assert(html.includes('role="region" aria-label="Вопросы и ответы"'));
assert(html.includes('role="region" aria-label="Контакты и время приёма"'));
assert(/\.history-narrative\{[^}]*overflow:auto/.test(css));
assert(/\.contact\.viewport-section \.contact-content\{height:auto;[^}]*overflow:visible/.test(css));
assert(/\.history-narrative\{[^}]*scrollbar-width:none/.test(css));
assert(!/\.contact[^{}]*\{[^}]*overflow:(?:auto|scroll)/.test(css));
assert(css.includes('.history-narrative::-webkit-scrollbar{display:none;width:0;height:0}'));
assert(/\.viewport-section\{[^}]*height:100dvh/.test(css));
assert(css.includes('filter:grayscale(1)') && css.includes('filter:grayscale(0)'));
console.log('Fullscreen section scope, four devices, keyboard scroll regions and review colors passed');
